const assert=require('node:assert/strict');
const {updateTripSettings}=require('./travel-globe/dist/prototype/core.js');
const visit=(uid,place='ohori')=>({uid,place,duration:75,fixed:'14:00'});
const original={id:'trip',name:'후쿠오카',city:'fukuoka',date:'2026-11-06',hotel:{name:'숙소'},days:[{start:'08:00',visits:[visit('a')]},{start:'10:00',visits:[]},{start:'11:00',visits:[visit('b'),visit('c')]},{start:'09:00',visits:[visit('d')]}]};
const before=structuredClone(original);
const settings={name:'후쿠오카 가을 여행',date:'2026-11-12',dayCount:2,overflow:'hold'};
const held=updateTripSettings(original,settings);
assert.deepEqual(original,before,'editing must not mutate original before commit');
assert.deepEqual(held.unassigned.map(v=>v.uid),['b','c','d']);
assert.deepEqual(held.unassigned.map(v=>v.originalDay),[3,3,4]);
assert.equal(held.unassigned[0].fixed,'14:00');assert.equal(held.unassigned[0].duration,75);
assert.deepEqual(held.hotel,original.hotel);assert.equal(held.days.length,2);
const moved=updateTripSettings(original,{...settings,overflow:'move'});
assert.deepEqual(moved.days[1].visits.map(v=>v.uid),['b','c','d']);
assert.equal(moved.days[1].visits[0].fixed,'14:00');assert.equal(moved.unassigned.length,0);
const expanded=updateTripSettings(held,{...settings,dayCount:5});
assert.equal(expanded.days.length,5);assert.equal(expanded.unassigned.length,3);
assert.deepEqual(expanded.days[2].visits,[]);assert.notEqual(expanded.days[2].visits,expanded.days[3].visits);
const one=updateTripSettings(held,{...settings,dayCount:1});
assert.equal(one.days.length,1);assert.equal(one.unassigned.length,3);
assert.throws(()=>updateTripSettings(original,{...settings,overflow:''}));
for(const dayCount of [0,15,2.5,NaN])assert.throws(()=>updateTripSettings(original,{...settings,dayCount}));
for(const date of ['2026-02-30','2026-13-01','bad'])assert.throws(()=>updateTripSettings(original,{...settings,date}));
assert.equal(updateTripSettings(original,{...settings,date:''}).date,'');
assert.throws(()=>updateTripSettings(original,{...settings,name:'  '}));
const reloaded=JSON.parse(JSON.stringify(held));
assert.deepEqual(reloaded.unassigned,held.unassigned);
const shortenedAgain=updateTripSettings({...held,days:[held.days[0],{visits:[visit('e')]}]},{...settings,dayCount:1});
assert.deepEqual(shortenedAgain.unassigned.map(v=>v.uid),['b','c','d','e']);
console.log('Passed: hold/move, duration/fixed-time preservation, expansion, repeated shrink, validation, original immutability and serialized recovery');
